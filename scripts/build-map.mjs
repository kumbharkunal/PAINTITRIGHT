// Builds the Visit section's map facade from OpenStreetMap data (© OpenStreetMap
// contributors, ODbL): a dark, static SVG of the streets around Hog Market, Rajendra
// Place, plus a small data module with the pin, the metro station and road labels (drawn
// as HTML so they use the site's fonts). No map tiles or scripts at runtime.
// Usage: node scripts/build-map.mjs [cached-overpass.json]
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const PIN = { lat: 28.6446717, lon: 77.1772307 }; // Hog Market point (TODO(client): exact shop pin)
const W = 1200, H = 900, PX_PER_M = 1.05;
const BBOX = [28.6385, 77.17, 28.651, 77.1845];

let osm;
if (process.argv[2]) osm = JSON.parse(readFileSync(process.argv[2], "utf8"));
else {
  const q = `[out:json][timeout:25];(way["highway"~"^(trunk|primary|secondary|tertiary|residential|unclassified|service|living_street|primary_link|secondary_link|tertiary_link)$"](${BBOX});way["railway"~"^(subway|rail|light_rail)$"](${BBOX});node["railway"="station"](${BBOX}););out geom;`;
  const r = await fetch("https://overpass-api.de/api/interpreter", { method: "POST", body: new URLSearchParams({ data: q }), headers: { "User-Agent": "paintitright-site-build/1.0" } });
  osm = await r.json();
}

const mPerLon = 111320 * Math.cos((PIN.lat * Math.PI) / 180), mPerLat = 110574;
const proj = (lat, lon) => [W / 2 + (lon - PIN.lon) * mPerLon * PX_PER_M, H / 2 - (lat - PIN.lat) * mPerLat * PX_PER_M];

// Douglas–Peucker
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts.at(-1)];
  let idx = -1, max = 0;
  const dx = b[0] - a[0], dy = b[1] - a[1], len = Math.hypot(dx, dy) || 1;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + b[0] * a[1] - b[1] * a[0]) / len;
    if (d > max) { max = d; idx = i; }
  }
  if (max <= tol) return [a, b];
  return [...simplify(pts.slice(0, idx + 1), tol).slice(0, -1), ...simplify(pts.slice(idx), tol)];
}
const r1 = (n) => Math.round(n * 10) / 10;
const toD = (pts) => "M" + pts.map(([x, y]) => `${r1(x)} ${r1(y)}`).join("L");

const CLASS = (t) => {
  if (/^(trunk|primary|secondary)(_link)?$/.test(t.highway)) return "major";
  if (/^tertiary(_link)?$/.test(t.highway)) return "mid";
  if (/^(residential|unclassified|living_street)$/.test(t.highway)) return "minor";
  if (t.highway === "service") return "service";
  if (t.railway) return "rail";
  return null;
};
const groups = { service: [], minor: [], mid: [], major: [], rail: [] };
const named = new Map();
for (const e of osm.elements) {
  if (e.type !== "way" || !e.geometry) continue;
  const cls = CLASS(e.tags);
  if (!cls) continue;
  const pts = simplify(e.geometry.map((g) => proj(g.lat, g.lon)), 0.9);
  groups[cls].push(toD(pts));
  if ((cls === "major" || cls === "mid") && e.tags.name) {
    const list = named.get(e.tags.name) ?? [];
    list.push({ pts, cls });
    named.set(e.tags.name, list);
  }
}

const STYLE = {
  service: 'stroke="#15181C" stroke-width="3"',
  minor: 'stroke="#1E2227" stroke-width="5"',
  mid: 'stroke="#2C3138" stroke-width="9"',
  major: 'stroke="#3A4048" stroke-width="15"',
  rail: 'stroke="#6F737A" stroke-width="2.5" stroke-dasharray="10 8"',
};
const body = Object.entries(groups).map(([k, ds]) => `<path d="${ds.join("")}" ${STYLE[k]}/>`).join("");
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}"><rect width="${W}" height="${H}" fill="#0B0C0F"/><g fill="none" stroke-linecap="round" stroke-linejoin="round">${body}</g></svg>\n`;
mkdirSync("public/map", { recursive: true });
writeFileSync("public/map/visit.svg", svg);

// labels: for each named road, the longest in-view segment; angle kept readable (−90..90)
const inView = ([x, y]) => x > 60 && x < W - 60 && y > 50 && y < H - 50;
const labels = [];
const WANT = ["Pusa Road", "Patel Road", "Shankar Road", "Govind Lal Sikka Marg"];
for (const name of WANT) {
  const parts = named.get(name);
  if (!parts) continue;
  let best = null;
  for (const { pts } of parts) for (let i = 0; i < pts.length - 1; i++) {
    const [a, b] = [pts[i], pts[i + 1]];
    if (!inView(a) || !inView(b)) continue;
    const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
    if (!best || len > best.len) best = { a, b, len };
  }
  if (!best) continue;
  let ang = (Math.atan2(best.b[1] - best.a[1], best.b[0] - best.a[0]) * 180) / Math.PI;
  if (ang > 90) ang -= 180;
  if (ang < -90) ang += 180;
  labels.push({ text: name, x: r1(((best.a[0] + best.b[0]) / 2 / W) * 100), y: r1(((best.a[1] + best.b[1]) / 2 / H) * 100), angle: r1(ang) });
}
const st = osm.elements.find((e) => e.type === "node" && e.tags?.name);
const [sx, sy] = st ? proj(st.lat, st.lon) : [null, null];
const data = `// Generated by scripts/build-map.mjs from OpenStreetMap data (© OpenStreetMap contributors).
// Positions are percentages of the 1200×900 map (public/map/visit.svg).
export const MAP = {
  pin: { x: 50, y: 50, lat: ${PIN.lat}, lon: ${PIN.lon} },
  station: ${st ? JSON.stringify({ name: `${st.tags.name} metro`, x: r1((sx / W) * 100), y: r1((sy / H) * 100) }) : "null"},
  labels: ${JSON.stringify(labels)},
} as const;
`;
mkdirSync("src/content", { recursive: true });
writeFileSync("src/content/map-data.ts", data);
console.log("map svg", svg.length, "bytes;", labels.length, "labels;", st ? `station ${st.tags.name}` : "no station");
